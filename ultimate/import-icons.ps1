param([string]$Revision = '1ef60af944de207e0d5176905a0759ba12e6ee8d')
$ErrorActionPreference = 'Stop'
$names = @('play','pause','skip-back','skip-forward','fullscreen','lock-keyhole','volume-2','captions','ellipsis-vertical','plus','search','refresh-cw','list-video','clock','settings-2','x','external-link')
$source = Join-Path $PSScriptRoot 'icons'
New-Item -ItemType Directory -Force -Path $source | Out-Null
$invariant = [Globalization.CultureInfo]::InvariantCulture
function Num($node, $attribute, $fallback=0) {
    $value = $node.GetAttribute($attribute)
    if ($value -eq '') { return [double]$fallback }
    return [double]::Parse($value, $invariant)
}
foreach ($name in $names) {
    $file = Join-Path $source "$name.svg"
    Invoke-WebRequest "https://raw.githubusercontent.com/lucide-icons/lucide/$Revision/icons/$name.svg" -OutFile $file
    [xml]$svg = Get-Content -LiteralPath $file -Raw
    $paths = [Collections.Generic.List[string]]::new()
    foreach ($node in $svg.DocumentElement.ChildNodes) {
        if ($node.NodeType -ne [Xml.XmlNodeType]::Element) { continue }
        $d = switch ($node.LocalName) {
            'path' { $node.GetAttribute('d') }
            'line' { "M $(Num $node x1) $(Num $node y1) L $(Num $node x2) $(Num $node y2)" }
            'circle' {
                $x=Num $node cx; $y=Num $node cy; $r=Num $node r
                "M $($x-$r) $y A $r $r 0 1 0 $($x+$r) $y A $r $r 0 1 0 $($x-$r) $y"
            }
            'rect' {
                $x=Num $node x; $y=Num $node y; $w=Num $node width; $h=Num $node height; $r=Num $node rx
                "M $($x+$r) $y H $($x+$w-$r) Q $($x+$w) $y $($x+$w) $($y+$r) V $($y+$h-$r) Q $($x+$w) $($y+$h) $($x+$w-$r) $($y+$h) H $($x+$r) Q $x $($y+$h) $x $($y+$h-$r) V $($y+$r) Q $x $y $($x+$r) $y Z"
            }
            'polyline' { 'M ' + $node.GetAttribute('points') }
            'polygon' { 'M ' + $node.GetAttribute('points') + ' Z' }
            default { throw "Unsupported SVG element $($node.LocalName) in $name" }
        }
        $escaped = [Security.SecurityElement]::Escape($d)
        $paths.Add("    <path android:pathData=`"$escaped`" android:fillColor=`"#00000000`" android:strokeColor=`"#FFFFFFFF`" android:strokeWidth=`"2`" android:strokeLineCap=`"round`" android:strokeLineJoin=`"round`" />")
    }
    $output = "<!-- Lucide $Revision; see assets/Lucide-LICENSE.txt. Generated by import-icons.ps1. -->`n<vector xmlns:android=`"http://schemas.android.com/apk/res/android`" android:width=`"24dp`" android:height=`"24dp`" android:viewportWidth=`"24`" android:viewportHeight=`"24`">`n$($paths -join "`n")`n</vector>`n"
    [IO.File]::WriteAllText((Join-Path $PSScriptRoot "src/main/res/drawable/ui_$($name.Replace('-','_')).xml"), $output)
}
Invoke-WebRequest "https://raw.githubusercontent.com/lucide-icons/lucide/$Revision/LICENSE" -OutFile (Join-Path $PSScriptRoot 'src/main/assets/Lucide-LICENSE.txt')
